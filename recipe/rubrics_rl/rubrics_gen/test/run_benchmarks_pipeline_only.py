#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from run_olympiabench_compare import ensure_dir, load_suite_records, run_cmd, to_pipeline_record, write_jsonl


def parse_args() -> argparse.Namespace:
    script_dir = Path(__file__).resolve().parent
    rubrics_gen_dir = script_dir.parent

    parser = argparse.ArgumentParser(description="Run pipeline-only rubrics generation on multiple benchmarks")
    parser.add_argument(
        "--suites",
        type=str,
        default="olympiadbench,mathvista,mathverse,mathvision,mmk12",
        help="Comma-separated suites",
    )
    parser.add_argument("--num_samples", type=int, default=20)

    default_dataset_root = script_dir.parents[4] / "dataset"
    parser.add_argument("--dataset_cache_root", type=Path, default=default_dataset_root)
    parser.add_argument("--output_dir", type=Path, default=script_dir / "outputs" / "multi_benchmark_pipeline_only")
    parser.add_argument(
        "--prepared_from_sft_root",
        type=Path,
        default=script_dir / "outputs" / "multi_benchmark_sft_only",
        help="Root dir of prepared benchmark data generated by run_benchmarks_sft_only.py",
    )

    parser.add_argument("--olympiadbench_source", type=str, default=str(default_dataset_root / "OlympiadBench"))
    parser.add_argument("--mathvista_source", type=str, default=str(default_dataset_root / "MathVista"))
    parser.add_argument("--mathverse_source", type=str, default=str(default_dataset_root / "MathVerse"))
    parser.add_argument("--mathvision_source", type=str, default=str(default_dataset_root / "MathVision"))
    parser.add_argument("--mmk12_source", type=str, default=str(default_dataset_root / "MMK12"))

    parser.add_argument("--pipeline_script", type=Path, default=rubrics_gen_dir / "pipeline.py")
    parser.add_argument("--pipeline_gpu_memory_utilization", type=float, default=0.6)
    parser.add_argument("--pipeline_max_model_len", type=int, default=None)
    parser.add_argument("--pipeline_max_num_seqs", type=int, default=64)
    return parser.parse_args()


def pick_prepared_file(suite_dir: Path, num_samples: int) -> Path | None:
    candidates = [
        suite_dir / f"first{num_samples}.jsonl",
        suite_dir / "first20.jsonl",  # backward-compatible with existing script output
    ]
    for path in candidates:
        if path.exists():
            return path
    return None


def read_jsonl_rows(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


def main() -> None:
    args = parse_args()
    if args.num_samples <= 0:
        raise ValueError("--num_samples must be > 0")
    if not args.pipeline_script.exists():
        raise FileNotFoundError(f"Pipeline script not found: {args.pipeline_script}")

    suite_list = [x.strip().lower() for x in args.suites.split(",") if x.strip()]
    source_overrides = {
        "olympiadbench": str(Path(args.olympiadbench_source).resolve()),
        "mathvista": str(Path(args.mathvista_source).resolve()),
        "mathverse": str(Path(args.mathverse_source).resolve()),
        "mathvision": str(Path(args.mathvision_source).resolve()),
        "mmk12": str(Path(args.mmk12_source).resolve()),
    }

    ensure_dir(args.output_dir)
    summary: dict[str, Any] = {}

    for suite in suite_list:
        print(f"\n===== Running Pipeline suite: {suite} =====", flush=True)
        suite_dir = args.output_dir / suite
        ensure_dir(suite_dir)

        sft_suite_dir = args.prepared_from_sft_root / suite
        sft_prepared_file = pick_prepared_file(sft_suite_dir, args.num_samples)
        sft_image_dir = sft_suite_dir / "images"

        if sft_prepared_file is not None:
            rows = read_jsonl_rows(sft_prepared_file)
            image_dir = sft_image_dir
            if len(rows) > args.num_samples:
                rows = rows[: args.num_samples]
                input_file = suite_dir / f"first{args.num_samples}.jsonl"
                write_jsonl(input_file, rows)
                print(
                    f"[{suite}] reuse+truncate prepared file from SFT-only: {sft_prepared_file} -> {input_file}",
                    flush=True,
                )
            else:
                input_file = sft_prepared_file
                print(f"[{suite}] reuse prepared file from SFT-only: {input_file}", flush=True)
            prepared_samples = len(rows)
        else:
            print(f"[{suite}] no prepared file found under {sft_suite_dir}, fallback to local extraction", flush=True)
            image_dir = suite_dir / "images"
            ensure_dir(image_dir)

            raw_items = load_suite_records(
                suite_name=suite,
                cache_root=args.dataset_cache_root,
                num_samples=args.num_samples,
                source_override=source_overrides[suite],
            )

            rows = []
            for i, item in enumerate(raw_items, start=1):
                try:
                    row = to_pipeline_record(suite, item, i, image_dir)
                except Exception as e:
                    print(f"[warn] skip sample {i} in {suite}: {e}", flush=True)
                    continue
                if not row.get("question"):
                    continue
                rows.append(row)
                if len(rows) >= args.num_samples:
                    break

            input_file = suite_dir / f"first{args.num_samples}.jsonl"
            write_jsonl(input_file, rows)
            prepared_samples = len(rows)
            print(f"[{suite}] prepared {prepared_samples} samples -> {input_file}", flush=True)

        pipeline_dir = suite_dir / "pipeline"
        pipeline_cmd = [
            sys.executable,
            str(args.pipeline_script),
            "--input_file",
            str(input_file),
            "--cot_raw_out",
            str(pipeline_dir / "cot_raw.jsonl"),
            "--cot_filtered_out",
            str(pipeline_dir / "cot_filtered.jsonl"),
            "--filter_raw_out",
            str(pipeline_dir / "filter_raw.jsonl"),
            "--filter_filtered_out",
            str(pipeline_dir / "filter_filtered.jsonl"),
            "--rubrics_raw_out",
            str(pipeline_dir / "rubrics_raw.jsonl"),
            "--rubrics_filtered_out",
            str(pipeline_dir / "rubrics_filtered.jsonl"),
            "--gpu_memory_utilization",
            str(args.pipeline_gpu_memory_utilization),
            "--max_num_seqs",
            str(args.pipeline_max_num_seqs),
            "--image_base_path",
            str(image_dir),
        ]
        if args.pipeline_max_model_len is not None:
            pipeline_cmd.extend(["--max_model_len", str(args.pipeline_max_model_len)])
        run_cmd(pipeline_cmd)

        summary[suite] = {
            "prepared_samples": prepared_samples,
            "prepared_file": str(input_file),
            "prepared_from_sft": sft_prepared_file is not None,
            "pipeline_output_dir": str(pipeline_dir),
            "pipeline_rubrics_filtered": str(pipeline_dir / "rubrics_filtered.jsonl"),
        }

    summary_path = args.output_dir / "summary.json"
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n[done] summary -> {summary_path}", flush=True)


if __name__ == "__main__":
    main()
